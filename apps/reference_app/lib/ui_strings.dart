/// Everything the app says to the user, in the app's own language: card
/// titles and texts, buttons, dialogs and toasts. Ten languages, keyed by
/// ISO 639-3 code, English as the fallback for a language that lacks a
/// string.
///
/// Placeholders in braces are filled by [fmt]: `{c}` a command phrase,
/// `{w}` a word, `{s}` a stretch of text or a store, `{p}` a provider,
/// `{e}` an error, `{n}`/`{t}` take counts, `{l}` START/STOP, `{a}` the
/// app name, `{u}` the uses a provider was granted, `{r}` a reason.
class UiStrings {
  const UiStrings._(this.code, this._s);

  /// ISO 639-3 code, '' for English.
  final String code;
  final Map<String, String> _s;

  /// The strings of the language the app is set to; [of] is cheap, so the
  /// widgets that have no settings at hand read this.
  static UiStrings current = UiStrings.of('');

  /// Codes in the order of the picker.
  static const codes = ['eng', 'deu', 'fra', 'ita', 'spa', 'por', 'nld', 'hrv', 'srp', 'tur'];

  static UiStrings of(String code) => UiStrings._(code, _byCode[code] ?? _en);

  /// The string for [key]; English when this language lacks it.
  String operator [](String key) => _s[key] ?? _en[key] ?? key;

  /// [key] with its placeholders filled.
  String fmt(String key, Map<String, Object?> args) {
    var s = this[key];
    args.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
    return s;
  }

  /// The language's own name, for the picker.
  String get name => this['name'];
  String get appLanguage => this['appLanguage'];
  String get voiceStart => this['voiceStart'];
  String get voiceStop => this['voiceStop'];
  String get vocabularySaved => this['vocabularySaved'];
  String get insertedIntoTarget => this['insertedIntoTarget'];
  String get permissionNeeded => this['permissionNeeded'];

  String commandDone(String phrase) => fmt('commandDone', {'c': phrase});
  String commandRefused(String why) => fmt('commandRefused', {'w': why});
  String settingsNotSaved(String e) => fmt('settingsNotSaved', {'e': e});
  String savingFailed(String e) => fmt('savingFailed', {'e': e});
  String keySaved(String store) => fmt('keySaved', {'s': store});
  String keyRemoved(String provider) => fmt('keyRemoved', {'p': provider});
  String noKey(String provider) => fmt('noKey', {'p': provider});
  String learned(String word, String stretch) => fmt('learned', {'w': word, 's': stretch});
}

