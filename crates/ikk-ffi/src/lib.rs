//! Thin bindings. No logic lives here; everything delegates to `ikk-engine`.
//! `api.rs` will hold the flutter_rust_bridge surface, `ikk.udl` the UniFFI one.
//!
//! Also the single source for "About" data: version, build, and the legal
//! texts every shell must show (settings → About / Licenses).

pub mod engine;
pub mod voice;

use serde::{Deserialize, Serialize};

/// Everything an About screen shows about the core. The *app* version
/// (pubspec.yaml) is the shell's own and is shown next to this.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AboutInfo {
    /// Core version from the workspace `Cargo.toml` (`[workspace.package] version`).
    pub core_version: String,
    /// Build counter from `[workspace.metadata.ikk] build_number` in the root Cargo.toml.
    pub build_number: u32,
    pub git_sha: String,
    pub build_date: String,
    pub target_os: String,
    pub target_arch: String,
    /// SPDX id of the core crates (AGPL-3.0-or-later in both repos).
    pub core_license: String,
    pub providers: Vec<String>,
}

/// Build-time identity, e.g. `0.1.0 (build 7, a1b2c3d4e5) macos-aarch64`.
pub fn core_version() -> String {
    format!(
        "{} (build {}, {}) {}-{}",
        env!("CARGO_PKG_VERSION"),
        env!("IKK_BUILD_NUMBER"),
        env!("IKK_GIT_SHA"),
        std::env::consts::OS,
        std::env::consts::ARCH
    )
}

pub fn about() -> AboutInfo {
    AboutInfo {
        core_version: env!("CARGO_PKG_VERSION").into(),
        build_number: env!("IKK_BUILD_NUMBER").parse().unwrap_or(0),
        git_sha: env!("IKK_GIT_SHA").into(),
        build_date: env!("IKK_BUILD_DATE").into(),
        target_os: std::env::consts::OS.into(),
        target_arch: std::env::consts::ARCH.into(),
        core_license: env!("CARGO_PKG_LICENSE").into(),
        providers: provider_ids(),
    }
}

/// Provider ids compiled into this build.
pub fn provider_ids() -> Vec<String> {
    let mut reg = ikk_stt::ProviderRegistry::new();
    ikk_providers::register_all(&mut reg);
    reg.ids().into_iter().map(|p| p.0).collect()
}

/// Full license text of the repository this core was built from
/// (the LICENSE file at the repository root).
pub fn license_text() -> &'static str {
    include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/../../LICENSE"))
}

/// Copyright and project notice (the NOTICE file at the repository root).
pub fn notice_text() -> &'static str {
    include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/../../NOTICE"))
}

/// Third-party crate licenses, generated by `cargo about` (see README).
pub fn third_party_text() -> &'static str {
    include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/../../THIRD_PARTY.md"))
}

/// Input devices for the microphone picker.
pub fn list_mics() -> Result<Vec<ikk_audio::InputDevice>, String> {
    ikk_audio::list_input_devices().map_err(|e| e.to_string())
}

/// Platform config directory (desktop); mobile shells pass their own paths.
pub fn config_dir() -> Option<String> {
    ikk_settings::store::default_config_dir().map(|p| p.display().to_string())
}

pub fn settings_load(path: &str) -> Result<String, String> {
    let s = ikk_settings::Settings::load(std::path::Path::new(path)).map_err(|e| e.to_string())?;
    s.to_json().map_err(|e| e.to_string())
}

pub fn settings_save(path: &str, json: &str) -> Result<(), String> {
    let s = ikk_settings::Settings::from_json(json).map_err(|e| e.to_string())?;
    s.save(std::path::Path::new(path)).map_err(|e| e.to_string())
}

pub fn consent_load(path: &str) -> Result<String, String> {
    let c = ikk_consent::ConsentState::load(std::path::Path::new(path)).map_err(|e| e.to_string())?;
    serde_json::to_string_pretty(&c).map_err(|e| e.to_string())
}

pub fn consent_save(path: &str, json: &str) -> Result<(), String> {
    let c: ikk_consent::ConsentState = serde_json::from_str(json).map_err(|e| e.to_string())?;
    c.save(std::path::Path::new(path)).map_err(|e| e.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn about_is_populated() {
        let a = about();
        assert_eq!(a.core_version, env!("CARGO_PKG_VERSION"));
        assert!(!a.git_sha.is_empty());
        assert!(a.build_number >= 1);
        assert_eq!(a.core_license, "AGPL-3.0-or-later");
        assert!(a.providers.contains(&"deepgram".to_string()));
        assert!(license_text().len() > 100);
        assert!(notice_text().contains("Stephan Korner"));
        assert!(!third_party_text().is_empty());
    }

    /// Consent names the real recipient: every compiled-in cloud provider
    /// needs an entry with a privacy policy in `ikk_consent::recipient_for`.
    #[test]
    fn every_cloud_provider_has_a_consent_entry() {
        let mut reg = ikk_stt::ProviderRegistry::new();
        ikk_providers::register_all(&mut reg);
        for id in reg.ids() {
            let p = reg.get(&id).unwrap();
            if p.capabilities().requires_network {
                let r = ikk_consent::recipient_for(&id.0, p.display_name());
                assert!(!r.privacy_url.is_empty(), "{} has no consent entry", id.0);
            }
        }
    }
}
